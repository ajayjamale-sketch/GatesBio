import React, { useState } from 'react';
import { Box } from '@mui/material';
import BiotechIcon from '@mui/icons-material/Biotech';
import ScienceIcon from '@mui/icons-material/Science';
import AutoAwesomeIcon from '@mui/icons-material/AutoAwesome';
import ArticleIcon from '@mui/icons-material/Article';
import {
  AI_RESEARCH_INSIGHTS,
  INITIAL_BIO_DATASETS,
  INITIAL_COLLABORATION_MESSAGES,
  INITIAL_EXPERIMENTS,
  INITIAL_PROJECTS,
  INITIAL_SAMPLE_TEST_REQUESTS,
  PUBLICATION_RECORDS,
} from '../../data/roleDashboardData';
import type {
  AiInsightItem,
  BioDatasetRecord,
  CollaborationMessage,
  DashboardSession,
  ExperimentRun,
  PublicationRecord,
  ResearchProjectItem,
  SampleTestRequest,
} from '../../types/dashboard';
import { KpiStatCard } from '../../components/app/shared/KpiStatCard';
import { ScientistProjectsPanel } from '../../components/app/scientist/ScientistProjectsPanel';
import { ScientistElnWorkspace } from '../../components/app/scientist/ScientistElnWorkspace';
import { ScientistAnalyticsPanel } from '../../components/app/scientist/ScientistAnalyticsPanel';
import { ScientistAiPanel } from '../../components/app/scientist/ScientistAiPanel';
import { ScientistDatasetsPanel } from '../../components/app/scientist/ScientistDatasetsPanel';
import { ScientistCollaborationPanel } from '../../components/app/scientist/ScientistCollaborationPanel';
import { ScientistPublicationsPanel } from '../../components/app/scientist/ScientistPublicationsPanel';

interface ResearchScientistDashboardProps {
  session: DashboardSession;
  activeNavId: string;
  searchQuery: string;
  onSelectNav: (navId: string) => void;
  onNotify: (msg: string) => void;
}

export const ResearchScientistDashboard: React.FC<ResearchScientistDashboardProps> = ({
  session,
  activeNavId,
  searchQuery,
  onSelectNav,
  onNotify,
}) => {
  const [projects, setProjects] = useState<ResearchProjectItem[]>(INITIAL_PROJECTS);
  const [experiments, setExperiments] = useState<ExperimentRun[]>(INITIAL_EXPERIMENTS);
  const [selectedExpId, setSelectedExpId] = useState<string>(INITIAL_EXPERIMENTS[0].id);
  const [sampleRequests, setSampleRequests] = useState<SampleTestRequest[]>(INITIAL_SAMPLE_TEST_REQUESTS);
  const [datasets, setDatasets] = useState<BioDatasetRecord[]>(INITIAL_BIO_DATASETS);
  const [aiInsights, setAiInsights] = useState<AiInsightItem[]>(AI_RESEARCH_INSIGHTS);
  const [messages, setMessages] = useState<CollaborationMessage[]>(INITIAL_COLLABORATION_MESSAGES);
  const [publications, setPublications] = useState<PublicationRecord[]>(PUBLICATION_RECORDS);

  const q = searchQuery.trim().toLowerCase();
  const matchesQuery = (fields: (string | undefined)[]) =>
    !q || fields.some((f) => f?.toLowerCase().includes(q));

  const filteredProjects = projects.filter((p) =>
    matchesQuery([p.id, p.title, p.grantCode, p.hypothesis, p.leadPi])
  );
  const filteredDatasets = datasets.filter((d) =>
    matchesQuery([d.id, d.name, d.format, ...d.ontologyTags])
  );
  const filteredInsights = aiInsights.filter((i) =>
    matchesQuery([i.title, i.summary, i.category, i.sourceRef])
  );
  const filteredPublications = publications.filter((p) =>
    matchesQuery([p.id, p.title, p.journalOrPatent, p.owners, p.doi])
  );

  const activeExperiment = experiments.find((e) => e.id === selectedExpId) ?? experiments[0];
  const activeSteps = activeExperiment?.steps ?? [];

  const handleAppendProtocolStep = (stepTitle: string) => {
    if (!activeExperiment) return;
    const newStep = {
      id: `step-ai-${Date.now()}`,
      label: `AI Protocol Step: ${stepTitle}`,
      targetNote: 'Generated by AI Lab Assistant',
      completed: false,
    };
    setExperiments((prev) =>
      prev.map((exp) =>
        exp.id === activeExperiment.id
          ? { ...exp, steps: [...(exp.steps ?? []), newStep] }
          : exp
      )
    );
    onSelectNav('eln');
    onNotify(`Appended protocol step to ${activeExperiment.id}.`);
  };

  const showAll = activeNavId === 'overview';
  const showSection = (id: string) => showAll || activeNavId === id;

  return (
    <Box sx={{ display: 'flex', flexDirection: 'column', gap: 3 }}>
      {/* KPI Row */}
      <Box
        sx={{
          display: 'grid',
          gridTemplateColumns: { xs: 'minmax(0, 1fr)', sm: 'repeat(2, minmax(0, 1fr))', lg: 'repeat(4, minmax(0, 1fr))' },
          gap: 2,
          '& > *': { minWidth: 0 },
        }}
      >
        <KpiStatCard
          title="Active Projects"
          value={projects.filter((p) => p.status !== 'Completed').length}
          delta="+1 this month"
          subtitle="Milestones & grants tracked"
          icon={<BiotechIcon sx={{ fontSize: 20 }} />}
          onClick={() => onSelectNav('projects')}
        />
        <KpiStatCard
          title="ELN Experiments"
          value={experiments.length}
          delta={`${activeSteps.filter((s) => s.completed).length}/${activeSteps.length} steps`}
          subtitle={`Run ${activeExperiment?.id ?? 'EXP-104'} active`}
          icon={<ScienceIcon sx={{ fontSize: 20 }} />}
          onClick={() => onSelectNav('eln')}
        />
        <KpiStatCard
          title="AI Literature Insights"
          value={aiInsights.length}
          delta="PubMed RAG"
          subtitle="Verified DOI syntheses"
          icon={<AutoAwesomeIcon sx={{ fontSize: 20 }} />}
          onClick={() => onSelectNav('ai-engine')}
        />
        <KpiStatCard
          title="Publications & IP"
          value={publications.length}
          delta={`${publications.filter((p) => p.status === 'Patent Filed').length} Patent Filed`}
          subtitle="Manuscripts & IDFs"
          icon={<ArticleIcon sx={{ fontSize: 20 }} />}
          onClick={() => onSelectNav('publications')}
        />
      </Box>

      {/* Projects & Milestones (2.2) */}
      {showSection('projects') && (
        <ScientistProjectsPanel
          session={session}
          projects={filteredProjects}
          onAddProject={(proj) => {
            setProjects((prev) => [proj, ...prev]);
            onNotify(`Created research project ${proj.id}: ${proj.title}`);
          }}
          onUpdateProject={(updated) =>
            setProjects((prev) => prev.map((p) => (p.id === updated.id ? updated : p)))
          }
          onNotify={onNotify}
        />
      )}

      {/* Split-Screen ELN, Plate Map & LIMS Sample Requests (2.2, 2.3) */}
      {showSection('eln') && (
        <ScientistElnWorkspace
          session={session}
          experiments={experiments}
          selectedExpId={selectedExpId}
          onSelectExpId={setSelectedExpId}
          onUpdateExperiment={(updated) =>
            setExperiments((prev) => prev.map((e) => (e.id === updated.id ? updated : e)))
          }
          onCreateExperiment={(created) => {
            setExperiments((prev) => [created, ...prev]);
            onNotify(`Initialized ELN run ${created.id}.`);
          }}
          sampleRequests={sampleRequests}
          onSubmitSampleRequest={(req) => {
            setSampleRequests((prev) => [req, ...prev]);
            onNotify(`Submitted LIMS request ${req.id} (${req.sampleId}) to Lab Queue.`);
          }}
          onNotify={onNotify}
        />
      )}

      {/* Scientific Visualizations & Research Velocity (2.11) */}
      {showAll && <ScientistAnalyticsPanel onNotify={onNotify} />}

      {/* AI Research Intelligence Engine (2.5) */}
      {showSection('ai-engine') && (
        <ScientistAiPanel
          insights={filteredInsights}
          onAddInsight={(ins) => setAiInsights((prev) => [ins, ...prev])}
          onAppendProtocolStep={handleAppendProtocolStep}
          onNotify={onNotify}
        />
      )}

      {/* Biological Datasets (2.4) & Collaboration (2.8) */}
      {(showSection('datasets') || showSection('collaboration')) && (
        <Box
          sx={{
            display: 'grid',
            gridTemplateColumns:
              showSection('datasets') && showSection('collaboration')
                ? { xs: 'minmax(0, 1fr)', lg: 'minmax(0, 1.15fr) minmax(0, 1fr)' }
                : 'minmax(0, 1fr)',
            gap: 2.5,
            '& > *': { minWidth: 0 },
          }}
        >
          {showSection('datasets') && (
            <ScientistDatasetsPanel
              datasets={filteredDatasets}
              onAddDataset={(ds) => setDatasets((prev) => [ds, ...prev])}
              onNotify={onNotify}
            />
          )}

          {showSection('collaboration') && (
            <ScientistCollaborationPanel
              session={session}
              messages={messages}
              onPostMessage={(msg) => setMessages((prev) => [msg, ...prev])}
              onAddReply={(messageId, text) =>
                setMessages((prev) =>
                  prev.map((m) =>
                    m.id === messageId
                      ? {
                          ...m,
                          replies: [
                            ...m.replies,
                            { id: `REP-${Date.now()}`, author: session.userName, time: 'Just now', text },
                          ],
                        }
                      : m
                  )
                )
              }
              onToggleReaction={(messageId, emoji) =>
                setMessages((prev) =>
                  prev.map((m) =>
                    m.id === messageId
                      ? {
                          ...m,
                          reactions: m.reactions.map((r) =>
                            r.emoji === emoji ? { ...r, count: r.count + 1 } : r
                          ),
                        }
                      : m
                  )
                )
              }
              onNotify={onNotify}
            />
          )}
        </Box>
      )}

      {/* Publications & IP (2.9) */}
      {showSection('publications') && (
        <ScientistPublicationsPanel
          session={session}
          publications={filteredPublications}
          onAddPublication={(pub) => setPublications((prev) => [pub, ...prev])}
          onUpdatePublication={(updated) =>
            setPublications((prev) => prev.map((p) => (p.id === updated.id ? updated : p)))
          }
          onNotify={onNotify}
        />
      )}
    </Box>
  );
};
